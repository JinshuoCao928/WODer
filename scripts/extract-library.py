#!/usr/bin/env python3
"""Generate src/library.js from the movement-library PDF.

Usage: python3 scripts/extract-library.py docs/reference/CrossFit_Complete_Movement_Library.pdf src/library.js
Needs `pdftotext` (brew install poppler). Fails loudly if the PDF doesn't parse as expected.
"""
import json, re, subprocess, sys
from collections import Counter

# Which form layout each format uses (spec §4). An unmapped format is an error.
LAYOUT = {
    'Strength': 'strength', 'Complex': 'strength',
    'AMRAP': 'amrap',
    'For Time': 'fortime', 'RFT': 'fortime', 'Chipper': 'fortime',
    'Ascending Ladder': 'fortime', 'Descending Ladder': 'fortime', 'Pyramid': 'fortime',
    'EMOM': 'intervals', 'E2MOM': 'intervals', 'Tabata': 'intervals', 'Intervals': 'intervals', 'Death By': 'intervals',
    'Max Effort': 'pr',
    'Partner WOD': 'other', 'Team WOD': 'other', 'Buy-In / Cash-Out': 'other',
}


def fail(msg):
    sys.exit(f'extract-library: {msg}')


def main(pdf, out):
    text = subprocess.run(['pdftotext', '-layout', pdf, '-'], capture_output=True, text=True, check=True).stdout
    lines = text.splitlines()

    movements = []
    for line in lines:
        m = re.match(r'\s*(CF-\d+)\s+(.+?)\s{2,}(\S.*?)\s*$', line)
        if m:
            movements.append({'id': m[1], 'name': m[2], 'group': m[3]})

    # Summary page: "Equipment Category  Movements" table, then "Format  Description" table.
    try:
        start = next(i for i, l in enumerate(lines) if l.strip().startswith('Equipment Category'))
        fstart = next(i for i, l in enumerate(lines) if l.strip().startswith('Format') and 'Description' in l)
    except StopIteration:
        fail('summary tables not found')
    group_counts = {}
    for l in lines[start + 1:fstart]:
        m = re.match(r'\s*(\S.*?)\s{2,}(\d+)\s*$', l)
        if m:
            group_counts[m[1]] = int(m[2])
    formats = [{'name': 'Strength', 'description': 'Sets × reps at a load', 'layout': 'strength'}]
    for l in lines[fstart + 1:]:
        m = re.match(r'\s*(\S.*?)\s{2,}(\S.*?)\s*$', l)
        if not m:
            if formats[1:]:
                break
            continue
        if m[1] not in LAYOUT:
            fail(f'format {m[1]!r} has no layout')
        formats.append({'name': m[1], 'description': m[2], 'layout': LAYOUT[m[1]]})

    ids = {m['id'] for m in movements}
    if len(movements) != 489 or len(ids) != 489:
        fail(f'expected 489 unique movements, got {len(movements)} rows / {len(ids)} ids')
    if dict(Counter(m['group'] for m in movements)) != group_counts:
        fail(f'group counts differ from summary page: {Counter(m["group"] for m in movements)} vs {group_counts}')

    with open(out, 'w') as f:
        f.write('// Generated by scripts/extract-library.py from docs/reference/CrossFit_Complete_Movement_Library.pdf. Do not edit.\n')
        f.write(f'export const MOVEMENTS = {json.dumps(movements, ensure_ascii=False)};\n')
        f.write(f'export const GROUP_COUNTS = {json.dumps(group_counts, ensure_ascii=False)};\n')
        f.write(f'export const FORMATS = {json.dumps(formats, ensure_ascii=False, indent=1)};\n')
    print(f'{len(movements)} movements, {len(group_counts)} groups, {len(formats)} formats')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        fail('usage: extract-library.py PDF OUT_JS')
    main(sys.argv[1], sys.argv[2])
